import FreeCAD, Part
F=Part.Shape(); F.read('work/out/front_cover.step')
B=Part.Shape(); B.read('work/out/back_cover.step')
def probe(shape,x,y,z,r=0.15):
    b=Part.makeBox(2*r,2*r,2*r,FreeCAD.Vector(x-r,y-r,z-r))
    return round(shape.common(b).Volume,4)
print("button boss centre z5 (hole expected 0):", probe(F,-22.337,-20.421,5.0))
print("button boss wall z5 (solid expected):", probe(F,-22.337+2.4,-20.421,5.0))
print("LED boss centre z5 (hole expected 0):", probe(F,-0.493,-19.405,5.0))
print("ledge z-0.45 y-45.1 (solid expected):", probe(F,0,-45.1,-0.45))
print("no ledge z-0.45 y-43.5 (void expected 0):", probe(F,0,-43.5,-0.45))
print("back cover boss ring z-1 (solid):", probe(B,-0.49,38.51,-1.0))
print("back cover screw hole z-5 (void 0):", probe(B,-0.49,38.51,-5.0))
print("back cover counterbore wall z-9.4 r2.6 (void):", probe(B,-0.49+2.6,38.51,-9.4))
print("board pocket: pcb area z1 clear:", probe(F,0,0,1.0))
print("window: z9.0 outside window (solid):", probe(F,-1.255,-14.0,9.0))
print("window: z9.0 in window (void):", probe(F,-1.255,-0.05,9.0))
print("usb slot z4 y25 x-29 (void):", probe(F,-29.0,25.3,4.2))
print("usb slot wall z4 y25 x-24 (solid? cavity):", probe(F,-24.0,25.3,4.2))
